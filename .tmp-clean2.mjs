let total = 0;
const missing = [];
for (const [file, pairs] of Object.entries(R)) {
  const txt = fs.readFileSync(file, "utf8");
  const eol = txt.includes("\r\n") ? "\r\n" : "\n";
  let lines = txt.split(/\r?\n/);
  for (const [oldL, newL] of pairs) {
    const hit = lines.filter((l) => l.trim() === oldL.trim()).length;
    if (hit === 0) { missing.push(file + " :: " + oldL.slice(0, 70)); continue; }
    if (newL === "") {
      lines = lines.filter((l) => l.trim() !== oldL.trim());
    } else {
      lines = lines.map((l) => (l.trim() === oldL.trim()
        ? l.slice(0, l.length - l.trimStart().length) + newL.trim()
        : l));
    }
    total++;
  }
  fs.writeFileSync(file, lines.join(eol));
}
